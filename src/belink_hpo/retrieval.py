"""Dense candidate retrieval over ontology names with a bi-encoder (SapBERT by default).

Build the index once:

    belink-hpo embed-terms --ontology hpo_terminology.json.gz --out_vectors index/hpo_vec.npy

Then retrieve candidates in Python:

    retriever = CandidateRetriever.from_files("index/hpo_vec.npy", "index/ontology_mapping.txt")
    retriever.retrieve(["brachydactyly"], standard_names=["Brachydactyly"])

or for a JSON file of mentions (the format used to build the training data):

    belink-hpo retrieve --input mentions.json --output_file mentions.json \
        --kb_vectors index/hpo_vec.npy --kb_mapping ontology_mapping.txt --top_k 30 \
        --apply_grf --use_rocchio --alpha 0.6
"""

from __future__ import annotations

import argparse
import gzip
import json
from pathlib import Path

import numpy as np
import torch
from tqdm.auto import tqdm

DEFAULT_ENCODER = "cambridgeltl/SapBERT-from-PubMedBERT-fulltext"
MAPPING_FILE = "ontology_mapping.txt"


def load_encoder(model_name=DEFAULT_ENCODER, device=None):
    from transformers import AutoModel, AutoTokenizer

    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModel.from_pretrained(model_name).to(device).eval()
    return model, tokenizer


def make_dense_vectors(model, tokenizer, texts, batch_size=1000, progress=True):
    """Embed texts as the [CLS] vector of the encoder. Returns a float32 array [len(texts), hidden]."""
    texts = list(texts)
    vectors = []
    starts = range(0, len(texts), batch_size)
    with torch.no_grad():
        for start in tqdm(starts, desc="Embedding") if progress else starts:
            batch = texts[start : start + batch_size]
            tokenized = tokenizer(batch, truncation=True, max_length=512, padding=True, return_tensors="pt")
            outputs = model(
                input_ids=tokenized["input_ids"].to(model.device),
                attention_mask=tokenized["attention_mask"].to(model.device),
            )
            vectors.append(outputs.last_hidden_state[:, 0, :].float().cpu())
    return torch.vstack(vectors).numpy()


def combine_with_feedback(mention_vectors, feedback_vectors, has_feedback, rocchio=True, alpha=0.6):
    """Generative relevance feedback: mix each mention vector with the vector of its standard name.

    rocchio=True  -> alpha * mention + (1 - alpha) * feedback
    rocchio=False -> plain average
    Rows without feedback keep the mention vector.
    """
    if rocchio:
        mixed = alpha * mention_vectors + (1 - alpha) * feedback_vectors
    else:
        mixed = (mention_vectors + feedback_vectors) / 2
    return np.where(np.asarray(has_feedback)[:, None], mixed, mention_vectors).astype(np.float32)


def search(query_vectors, kb_vectors, top_k):
    """Exact inner-product search. Returns the indices of the top_k rows of kb_vectors per query."""
    scores = query_vectors @ kb_vectors.T
    return np.argsort(-scores, axis=1, kind="stable")[:, :top_k]


def read_mapping(path):
    """Read 'id||name' lines, one per indexed name, in the same order as the vectors."""
    with open(path, encoding="utf-8") as f:
        return [line.strip() for line in f if line.strip()]


class CandidateRetriever:
    """Retrieve the top-k ontology names for a mention."""

    def __init__(self, kb_vectors, kb_entries, model, tokenizer):
        if len(kb_entries) != len(kb_vectors):
            raise ValueError(f"{len(kb_entries)} mapping lines but {len(kb_vectors)} vectors.")
        self.kb_vectors = kb_vectors
        self.kb_entries = kb_entries
        self.model = model
        self.tokenizer = tokenizer

    @classmethod
    def from_files(cls, kb_vectors, kb_mapping, model_name=DEFAULT_ENCODER, device=None):
        model, tokenizer = load_encoder(model_name, device)
        return cls(np.load(kb_vectors), read_mapping(kb_mapping), model, tokenizer)

    def retrieve(self, mentions, standard_names=None, top_k=30, rocchio=True, alpha=0.6):
        """Return, for each mention, a ranked list of {"id", "name"} candidates.

        ``standard_names`` (optional, one per mention, None where missing) are canonical
        names for the mentions, e.g. generated by an LLM. They are mixed into the query
        vector as relevance feedback. Ids are returned upper-cased ("HP:0001156").
        """
        results = []
        for row in self.retrieve_indices(mentions, standard_names, top_k, rocchio, alpha):
            cands = []
            for idx in row:
                cid, _, name = self.kb_entries[idx].partition("||")
                cands.append({"id": cid.strip().upper(), "name": name.strip()})
            results.append(cands)
        return results

    def retrieve_indices(self, mentions, standard_names=None, top_k=30, rocchio=True, alpha=0.6):
        """Like ``retrieve`` but returns row indices into the index, [len(mentions), top_k]."""
        mentions = list(mentions)
        queries = make_dense_vectors(self.model, self.tokenizer, mentions, progress=False)
        if standard_names is not None:
            has_feedback = [bool(s) for s in standard_names]
            if any(has_feedback):
                feedback = make_dense_vectors(
                    self.model, self.tokenizer,
                    [s if s else m for s, m in zip(standard_names, mentions)], progress=False,
                )
                queries = combine_with_feedback(queries, feedback, has_feedback, rocchio, alpha)
        return search(queries, self.kb_vectors, top_k)


# --------------------------------------------------------------------------- #
# Command line: build the index
# --------------------------------------------------------------------------- #

def embed_terms_main(argv=None):
    parser = argparse.ArgumentParser(
        prog="belink-hpo embed-terms",
        description="Embed ontology term names with a transformer model and save them as one .npy file",
    )
    parser.add_argument("--ontology", required=True, nargs="+",
                        help='One or more gzipped JSON files: a list of {"id": concept_id, "name": alias_text}')
    parser.add_argument("--model_name", default=DEFAULT_ENCODER, help="Embedding model to use")
    parser.add_argument("--out_vectors", required=True, help="Output .npy file with the dense vectors")
    args = parser.parse_args(argv)

    all_ids, all_texts = [], []
    for ont_path in args.ontology:
        print(f"Loading ontology: {ont_path}...")
        with gzip.open(ont_path, "rt", encoding="utf-8") as f:
            ontology = json.load(f)
        data = [(e["id"], e["name"].lower()) for e in ontology]
        print(f"   -> Added {len(data)} terms from {ont_path}")
        all_ids.extend(i for i, _ in data)
        all_texts.extend(t for _, t in data)

    print(f"Total terms to vectorize: {len(all_texts)}")
    if not all_texts:
        raise SystemExit("No terms found.")

    out_path = Path(args.out_vectors)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    mapping_path = out_path.parent / MAPPING_FILE
    print(f"Saving ID/Text mapping to {mapping_path}...")
    with open(mapping_path, "w", encoding="utf-8") as f:
        for oid, otext in zip(all_ids, all_texts):
            f.write(f"{oid}||{' '.join(otext.split())}\n")

    print(f"Loading {args.model_name} tokenizer and model...")
    model, tokenizer = load_encoder(args.model_name)
    print(f"device={model.device}")

    vectors = make_dense_vectors(model, tokenizer, all_texts)
    print(f"Final shape: {vectors.shape}")
    np.save(out_path, vectors)
    print(f"Saved to {out_path}")


# --------------------------------------------------------------------------- #
# Command line: retrieve candidates for a JSON file of mentions
# --------------------------------------------------------------------------- #

def retrieve_main(argv=None):
    parser = argparse.ArgumentParser(
        prog="belink-hpo retrieve",
        description="Retrieve candidates for a JSON file of mentions and write them back into each record",
    )
    parser.add_argument("--input", required=True,
                        help='JSON object of records, each with "label" and optionally "standard_name"')
    parser.add_argument("--output_file", required=True, help="Output JSON (may be the same file as --input)")
    parser.add_argument("--kb_vectors", required=True, help="Vectors written by embed-terms")
    parser.add_argument("--kb_mapping", default=MAPPING_FILE,
                        help="Mapping written by embed-terms; a bare file name is looked up next to --kb_vectors")
    parser.add_argument("--top_k", type=int, default=10, help="Max candidates")
    parser.add_argument("--model_name", default=DEFAULT_ENCODER, help="Embedding model; must match the index")
    parser.add_argument("--apply_grf", action="store_true", help='Use each record\'s "standard_name" as feedback')
    parser.add_argument("--use_rocchio", action="store_true", help="Weighted mix (alpha) instead of a plain average")
    parser.add_argument("--alpha", type=float, default=0.6, help="Weight of the mention vector with --use_rocchio")
    args = parser.parse_args(argv)

    with open(args.input, encoding="utf-8") as fp:
        records = json.load(fp)

    # one query per unique mention text
    standard_by_label = {}
    for record in records.values():
        standard_by_label.setdefault(record["label"], record.get("standard_name"))
    labels = list(standard_by_label)
    print(f"Loaded {len(labels)} unique mentions from {len(records)} records.")

    mapping_path = Path(args.kb_mapping)
    if not mapping_path.exists():
        mapping_path = Path(args.kb_vectors).parent / args.kb_mapping
    retriever = CandidateRetriever.from_files(args.kb_vectors, mapping_path, args.model_name)

    standard_names = [standard_by_label[label] for label in labels] if args.apply_grf else None
    if args.apply_grf:
        print(f"Applying feedback with alpha={args.alpha} and rocchio={args.use_rocchio}")
    print(f"Retrieving {args.top_k} candidates for each mention.")
    ranked = retriever.retrieve_indices(labels, standard_names, args.top_k, args.use_rocchio, args.alpha)

    # "id||name|id||name|..." exactly as the names appear in the mapping file
    by_label = {
        label: "|".join(retriever.kb_entries[idx] for idx in row) for label, row in zip(labels, ranked)
    }
    for record in records.values():
        record["candidates"] = by_label.get(record.get("label", ""), "")

    with open(args.output_file, "w", encoding="utf-8") as fp:
        json.dump(records, fp, indent=4, ensure_ascii=False)
    print(f"Wrote {args.output_file}")


def parse_candidates(candidate_string):
    """Parse 'id||name|id||name|...' into [{"id": ..., "name": ...}, ...]."""
    candidates = []
    for item in (candidate_string or "").replace("||", ">>").split("|"):
        if not item.strip():
            continue
        cid, _, name = item.partition(">>")
        candidates.append({"id": cid.strip(), "name": name.strip()})
    return candidates
